import numpy as np
import pandas as pd


class MetaLabelingClassifier:
    """
    Calibrated meta-labeling model predicting P(Success | Features).
    Trained on Phase 2 features to determine whether to Take, Skip, or Size
    proposals generated by Phase 3 rule strategies.
    """
    def __init__(self, l2_reg=1.0, learning_rate=0.05, n_epochs=200):
        self.l2_reg = float(l2_reg)
        self.lr = float(learning_rate)
        self.epochs = int(n_epochs)
        self.weights = None
        self.bias = 0.0
        self.mean = None
        self.std = None
        self.feature_names = []

    def _sigmoid(self, z):
        return 1.0 / (1.0 + np.exp(-np.clip(z, -25.0, 25.0)))

    def fit(self, X, y, feature_names=None):
        X_mat = np.array(X, dtype=float)
        y_vec = np.array(y, dtype=float)
        n_samples, n_features = X_mat.shape
        self.feature_names = feature_names or [f"f_{i}" for i in range(n_features)]

        # 1. Feature Standardization (Z-score)
        self.mean = np.mean(X_mat, axis=0)
        self.std = np.std(X_mat, axis=0)
        self.std[self.std < 1e-8] = 1.0
        X_norm = (X_mat - self.mean) / self.std

        # 2. Train regularized logistic regression via Gradient Descent
        self.weights = np.zeros(n_features)
        self.bias = 0.0

        for _ in range(self.epochs):
            linear = np.dot(X_norm, self.weights) + self.bias
            preds = self._sigmoid(linear)

            # Gradients with L2 regularization
            error = preds - y_vec
            grad_w = (np.dot(X_norm.T, error) / n_samples) + (self.l2_reg * self.weights / n_samples)
            grad_b = np.mean(error)

            self.weights -= self.lr * grad_w
            self.bias -= self.lr * grad_b

        return self

    def predict_proba(self, X):
        X_mat = np.array(X, dtype=float)
        if self.weights is None:
            return np.full(len(X_mat), 0.5)
        X_norm = (X_mat - self.mean) / self.std
        linear = np.dot(X_norm, self.weights) + self.bias
        return self._sigmoid(linear)

    def predict_decision(self, feature_vector, threshold=0.55):
        prob = float(self.predict_proba(np.array([feature_vector]))[0])
        take = bool(prob >= threshold)
        # Kelly-style size scaling: higher probability -> higher allocation
        size_mult = round(float(min(1.5, max(0.2, 2.0 * (prob - 0.4)))), 2) if take else 0.0
        return {
            "take": take,
            "probability": round(prob, 4),
            "size_multiplier": size_mult
        }

    def get_feature_importance(self):
        if self.weights is None or not len(self.feature_names):
            return {}
        abs_w = np.abs(self.weights)
        total = np.sum(abs_w) or 1.0
        norm_imp = abs_w / total
        return {name: round(float(imp), 4) for name, imp in sorted(zip(self.feature_names, norm_imp), key=lambda x: x[1], reverse=True)}
